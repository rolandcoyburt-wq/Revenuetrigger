const assert=require('node:assert/strict'),fs=require('node:fs'),vm=require('node:vm');
const source=fs.readFileSync('frontend/public/assets/rt-marketing.js','utf8');
const functionSource=source.slice(source.indexOf('function heroPublicContext'),source.indexOf('async function loadMarketingSignals'));
const sandbox={RTUI:{esc:x=>String(x).replace(/</g,'&lt;'),money:x=>'$'+x.value.toLocaleString('en-US')},Date};
vm.createContext(sandbox);vm.runInContext(functionSource,sandbox);
const now=new Date('2026-10-01T12:00:00Z');
const x={publicPreview:true,stage:'APPLICATION',date:'2026-09-30T12:00:00Z',value:850000,company:'SECRET COMPANY',address:'SECRET ADDRESS',actionIntelligence:{whyNow:'SECRET COMPANY at SECRET ADDRESS'}};
let result=sandbox.heroPublicContext(x,now);
assert(result.why.includes('Application activity recorded yesterday.'));
assert(result.why.includes('Estimated service opportunity: $850,000.'));
assert(!JSON.stringify(result).includes('SECRET'));
assert(!result.why.includes('property owner'));
assert(result.why.includes('onclick="openSignin()"'));
assert.equal((result.timeline.match(/●/g)||[]).length,1);
assert.equal((result.timeline.match(/○/g)||[]).length,2);
assert(result.timeline.includes('aria-current="step"><span>Application'));
result=sandbox.heroPublicContext({...x,stage:'PERMIT ISSUED'},now);
assert(result.timeline.includes('aria-current="step"><span>Permit issued'));
result=sandbox.heroPublicContext({...x,stage:null,date:'invalid',value:0},now);
assert(!result.why.includes('yesterday'));assert(!result.why.includes('$'));assert(!result.timeline.includes('●'));
assert(source.includes('rows.map(x=>opportunityCard(x,{preview:true}))'));
assert(source.includes('${triggerTimeline(rich)}'));
console.log('PASS hero-only summary, stage accuracy, hidden-detail exclusion, date/value fallbacks and sign-in CTA');
